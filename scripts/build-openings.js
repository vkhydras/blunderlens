// Builds shared/openings.js from the lichess chess-openings TSVs.
// Every position reached along a named line counts as "book"; the line's
// final position carries the opening's ECO code and name.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { Chess } from 'chess.js';

const epd = (fen) => fen.split(' ').slice(0, 4).join(' ');
const book = {};

for (const f of ['a', 'b', 'c', 'd', 'e']) {
  const rows = readFileSync(new URL(`./data/${f}.tsv`, import.meta.url), 'utf8').trim().split('\n').slice(1);
  for (const row of rows) {
    const [eco, name, pgn] = row.split('\t');
    const chess = new Chess();
    const sans = pgn.replace(/\d+\.(\.\.)?/g, ' ').trim().split(/\s+/);
    for (const san of sans) {
      chess.move(san);
      const key = epd(chess.fen());
      if (!(key in book)) book[key] = 0;
    }
    book[epd(chess.fen())] = [eco, name];
  }
}

mkdirSync(new URL('../shared/', import.meta.url), { recursive: true });
writeFileSync(new URL('../shared/openings.js', import.meta.url), `// Generated by scripts/build-openings.js — do not edit.\nexport default ${JSON.stringify(book)};\n`);
console.log(`wrote ${Object.keys(book).length} book positions`);
